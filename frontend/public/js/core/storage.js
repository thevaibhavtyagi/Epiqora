/**
 * DermAI Pro - Session Storage Management
 * Handles all application state persistence using sessionStorage
 */

const Storage = {
  // Keys
  KEYS: {
    IMAGE: 'dermai_image',
    ANALYSIS: 'dermai_analysis',
    QUESTIONS: 'dermai_questions', // NEW: Added key for questions
    ANSWERS: 'dermai_answers',
    REPORT: 'dermai_report',
    SESSION_ID: 'epiqora_session_id', // Telemetry Session Key
  },

  // --- TELEMETRY & TRACKING ---
  
  /**
   * Generates or retrieves a highly secure, anonymous session ID.
   * This tracks drop-offs but contains ZERO personal data.
   */
  getSessionId() {
    let sessionId = sessionStorage.getItem(this.KEYS.SESSION_ID);
    
    // If they don't have an ID yet, create one!
    if (!sessionId) {
      // Use the browser's built-in crypto for a professional-grade random string
      const randomPart = window.crypto && window.crypto.randomUUID 
        ? crypto.randomUUID() 
        : Math.random().toString(36).substring(2, 15);
        
      sessionId = `epiq-${randomPart}`;
      sessionStorage.setItem(this.KEYS.SESSION_ID, sessionId);
      console.log('🛡️ [Telemetry] Anonymous Session Started:', sessionId);
    }
    
    return sessionId;
  },

  // --- EXISTING CORE LOGIC ---

  /**
   * Save image data
   */
  saveImage(imageData) {
    sessionStorage.setItem(this.KEYS.IMAGE, imageData);
    console.log('[Storage] Image saved');
  },

  /**
   * Get saved image
   */
  getImage() {
    return sessionStorage.getItem(this.KEYS.IMAGE);
  },

  /**
   * Save analysis results
   */
  saveAnalysis(analysisData) {
    sessionStorage.setItem(this.KEYS.ANALYSIS, JSON.stringify(analysisData));
    console.log('[Storage] Analysis saved');
  },

  /**
   * Get saved analysis
   */
  getAnalysis() {
    const data = sessionStorage.getItem(this.KEYS.ANALYSIS);
    return data ? JSON.parse(data) : null;
  },

  // --- NEW: Question Storage ---
  /**
   * Save questions generated by AI
   */
  saveQuestions(questionsData) {
    sessionStorage.setItem(this.KEYS.QUESTIONS, JSON.stringify(questionsData));
    console.log('[Storage] Questions saved');
  },

  /**
   * Get saved questions
   */
  getQuestions() {
    const data = sessionStorage.getItem(this.KEYS.QUESTIONS);
    return data ? JSON.parse(data) : [];
  },
  // -----------------------------

  /**
   * Save question answers
   */
  saveAnswers(answersData) {
    sessionStorage.setItem(this.KEYS.ANSWERS, JSON.stringify(answersData));
    console.log('[Storage] Answers saved');
  },

  /**
   * Get saved answers
   */
  getAnswers() {
    const data = sessionStorage.getItem(this.KEYS.ANSWERS);
    return data ? JSON.parse(data) : null;
  },

  /**
   * Save report data
   */
  saveReport(reportData) {
    sessionStorage.setItem(this.KEYS.REPORT, JSON.stringify(reportData));
    console.log('[Storage] Report saved');
  },

  /**
   * Get saved report
   */
  getReport() {
    const data = sessionStorage.getItem(this.KEYS.REPORT);
    return data ? JSON.parse(data) : null;
  },

  /**
   * Clear all data
   */
  clearAll() {
    Object.values(this.KEYS).forEach(key => {
      sessionStorage.removeItem(key);
    });
    console.log('[Storage] All data cleared');
  },

  /**
   * Clear specific data
   */
  clear(key) {
    sessionStorage.removeItem(key);
    console.log('[Storage] Cleared:', key);
  },

  /**
   * Check if user has completed a specific step
   */
  hasCompleted(step) {
    switch(step) {
      case 'upload':
        return this.getImage() !== null;
      case 'analysis':
        return this.getAnalysis() !== null;
      case 'questions':
        return this.getAnswers() !== null;
      case 'report':
        return this.getReport() !== null;
      default:
        return false;
    }
  },
};